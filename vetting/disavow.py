"""
Google Search Console Disavow File Generator
Generates standards-compliant disavow files for toxic PBNs and spam backlinks.
Inspired by gunjanjaswal/Disavow-Generator.
"""

import re
import urllib.parse
from datetime import datetime
from pathlib import Path
from typing import List, Optional


def extract_domain(url: str) -> str:
    """Extracts root hostname from a URL."""
    raw = url.strip()
    if "://" not in raw:
        raw = "http://" + raw
    try:
        parsed = urllib.parse.urlparse(raw)
        return parsed.hostname or raw
    except Exception:
        return raw


def generate_disavow_content(
    items: List[str],
    domain_mode: bool = True,
    comment_header: Optional[str] = None
) -> str:
    """
    Constructs a Google-compliant disavow file string.
    Supports 'domain:example.com' or individual 'url:http://example.com/bad-page'.
    """
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
    lines = [
        "# Google Search Console Disavow File",
        f"# Generated by OmniLink Studio on: {timestamp}",
    ]
    if comment_header:
        lines.append(f"# Context: {comment_header}")
    lines.append("# Format: domain:example.com or url:https://example.com/path\n")

    seen = set()
    for item in items:
        clean = item.strip()
        if not clean or clean.startswith("#"):
            continue

        if domain_mode:
            domain = extract_domain(clean)
            if domain and domain not in seen:
                seen.add(domain)
                lines.append(f"domain:{domain}")
        else:
            if clean not in seen:
                seen.add(clean)
                lines.append(clean)

    return "\n".join(lines) + "\n"


def save_disavow_file(
    items: List[str],
    output_path: str,
    domain_mode: bool = True,
    comment_header: Optional[str] = None
) -> str:
    """Writes disavow content to the target file path."""
    content = generate_disavow_content(items, domain_mode=domain_mode, comment_header=comment_header)
    out_file = Path(output_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        f.write(content)
    return str(out_file.resolve())
